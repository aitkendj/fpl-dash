/**
 * Capture a live snapshot for offline development.
 *
 * Run with: npm run capture
 *
 * Writes `src/data/snapshot.ts` — a typed snapshot of the real FPL and
 * Sideline Quant data. The dashboard falls back to this when the live
 * sources are unreachable, so development works offline and the
 * fallback is a real capture rather than hand-written mock data.
 */
import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import {
  fetchBootstrapRaw,
  fetchEntry,
  fetchHistory,
  fetchPicks,
  fetchFixturesRaw,
} from "../src/lib/server/fpl"
import { fetchProjectionsRaw } from "../src/lib/server/sidelinequant"
import {
  applyProjections,
  buildElementContext,
  buildHistoryRows,
  buildProjectionLookup,
  buildSquad,
  transformElement,
} from "../src/lib/transform"
import type { DashboardPlayer, SquadPlayer } from "../src/lib/model"

async function main() {
  console.log("Fetching live data…")

  const [bootstrap, entry, history, fixtures, projections] = await Promise.all([
    fetchBootstrapRaw(),
    fetchEntry(),
    fetchHistory(),
    fetchFixturesRaw(),
    fetchProjectionsRaw(),
  ])

  const currentEvent =
    bootstrap.events.find((event) => event.is_current)?.id ?? entry.current_event
  const nextEvent =
    bootstrap.events.find((event) => event.is_next)?.id ?? currentEvent + 1

  const context = buildElementContext(bootstrap, fixtures, nextEvent)
  let players: DashboardPlayer[] = bootstrap.elements.map((element) =>
    transformElement(element, context)
  )
  players = applyProjections(players, buildProjectionLookup(projections))

  const picks = await fetchPicks(currentEvent)
  const squad: SquadPlayer[] = buildSquad(players, picks)

  // Only players with a projection are useful for the fallback tables.
  const withProjection = players.filter(
    (player) => player.sidelineQuantProjection !== null
  )

  const snapshot = {
    capturedAt: new Date().toISOString(),
    teamId: entry.id,
    managerName: entry.name,
    currentGameweek: currentEvent,
    nextGameweek: nextEvent,
    seasonLength: bootstrap.events.length,
    manager: {
      teamId: entry.id,
      name: entry.name,
      currentGameweek: currentEvent,
      nextGameweek: nextEvent,
      seasonLength: bootstrap.events.length,
      yearsActive: entry.years_active,
      totalPoints: entry.summary_overall_points,
      eventPoints: entry.summary_event_points,
      overallRank: entry.summary_overall_rank,
      eventRank: entry.summary_event_rank,
      bank: entry.last_deadline_bank,
      teamValue: entry.last_deadline_value,
      totalTransfers: entry.last_deadline_total_transfers,
      favouriteTeam: entry.favourite_team,
    },
    history: buildHistoryRows(history),
    chips: history.chips,
    squad,
    players: withProjection,
  }

  const target = resolve(process.cwd(), "src/data/snapshot.ts")
  writeFileSync(
    target,
    `/**
 * Captured live snapshot — ${snapshot.capturedAt}
 *
 * Generated by \`npm run capture\`. Used as the offline fallback when
 * the live FPL or Sideline Quant endpoints are unreachable. The shapes
 * match the live model exactly, so both paths run the same code.
 *
 * Do not edit by hand.
 */

import type {
  DashboardPlayer,
  GameweekHistoryRow,
  ManagerSummary,
  SquadPlayer,
} from "@/lib/model"

export const SNAPSHOT_CAPTURED_AT = ${JSON.stringify(snapshot.capturedAt)}

export const SNAPSHOT_MANAGER: ManagerSummary = ${JSON.stringify(snapshot.manager, null, 2)}

export const SNAPSHOT_HISTORY: GameweekHistoryRow[] = ${JSON.stringify(snapshot.history, null, 2)}

export const SNAPSHOT_CHIPS = ${JSON.stringify(snapshot.chips, null, 2)}

export const SNAPSHOT_SQUAD: SquadPlayer[] = ${JSON.stringify(snapshot.squad, null, 2)}

export const SNAPSHOT_PLAYERS: DashboardPlayer[] = ${JSON.stringify(snapshot.players, null, 2)}
`,
    "utf8"
  )

  console.log(
    `Captured ${snapshot.players.length} players, ${snapshot.squad.length} squad, ${snapshot.history.length} gameweeks`
  )
  console.log(`Written to ${target}`)
}

main().catch((error) => {
  console.error("Capture failed:", error)
  process.exit(1)
})
